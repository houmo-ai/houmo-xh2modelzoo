#!/usr/bin/env python3
"""build_mtp_hot_vocab.py — build hot-token vocab selection for MTP head K-trimming.

Inputs
------
- Tokenizer from --model (Qwen3.5-4B or compatible).
- Openclaw corpus counters under freqs/openclaw_{codex,copilot,vscode}.counter.pt
  (generated by pipeline 02_tokenize_openclaw.py; pass --rebuild-counters to re-run).
- Public corpus counters under freqs/public_{ceval_zh,c4_en,sharegpt_zh,wildchat_zh,
  legacy}.counter.pt  (generated by pipeline 03_build_public.py; pass --skip-public
  only if these already exist in freqs/).
- Category CSV: analysis/mtp_head_longtail/category_stats.csv
- Dialogue whitelist: analysis/mtp_head_longtail/v2_reranked/extras/dialogue_whitelist.json

Outputs  (under --output-dir, default: analysis/mtp_head_longtail/v2_reranked/selection/)
-------
- hot_ids_{K}.pt          torch.int64[K], ascending old token ids
- id_map_{K}.pt           {"old_to_new": int64[V](-1 for cold), "new_to_old": int64[K]}
- merged_counter.pt       dict[int→float] full weighted token frequencies
- selection_stats.json    per-source coverage + composition stats

Usage examples
--------------
# Fast path: all public counters already cached, skip re-downloading HF datasets
python examples/llm/qwen3_5/build_mtp_hot_vocab.py \\
    --model weights/Qwen3.5-4B \\
    --k-list 32000,48000,81920,82000 \\
    --skip-public

# Rebuild only openclaw counters from raw TSV (corpus must exist)
python examples/llm/qwen3_5/build_mtp_hot_vocab.py \\
    --model weights/Qwen3.5-4B \\
    --k-list 81920,82000 \\
    --rebuild-counters

# Full rebuild from scratch (downloads streaming HF datasets)
python examples/llm/qwen3_5/build_mtp_hot_vocab.py \\
    --model weights/Qwen3.5-4B \\
    --k-list 32000,48000,81920,82000
"""
