# ── Stage 02: tokenize openclaw raw TSV ──────────────────────────────────────

def build_openclaw_counters(model: str, corpus_dir: Path, freqs_dir: Path) -> None:
    """Tokenise openclaw_raw.tsv → per-source .counter.pt files (stage 02)."""
    raw = corpus_dir / "openclaw_raw.tsv"
    if not raw.exists():
        raise FileNotFoundError(
            f"openclaw_raw.tsv not found at {raw}. "
            "Run pipeline/01_extract_openclaw.sh first to extract from the DB."
        )
    freqs_dir.mkdir(parents=True, exist_ok=True)
    tok = AutoTokenizer.from_pretrained(model)
    buckets: dict[str, list[str]] = {"codex": [], "copilot": [], "vscode": []}
    t0 = time.time()
    with raw.open() as f:
        for line in f:
            parts = line.rstrip("\n").split("\t", 1)
            if len(parts) != 2:
                continue
            src, content = parts
            b = "codex" if src in ("codex", "claude") else (
                "copilot" if src == "copilot" else "vscode"
            )
            buckets[b].append(content)
    print(
        f"[02] load {time.time()-t0:.1f}s  "
        f"codex={len(buckets['codex'])} copilot={len(buckets['copilot'])} "
        f"vscode={len(buckets['vscode'])}"
    )
    stats = {}
    BATCH = 256
    for name, docs in buckets.items():
        t = time.time()
        c: Counter = Counter()
        for i in range(0, len(docs), BATCH):
            enc = tok(docs[i:i+BATCH], add_special_tokens=False)
            for ids in enc["input_ids"]:
                c.update(ids)
        torch.save(dict(c), freqs_dir / f"openclaw_{name}.counter.pt")
        stats[name] = {
            "msg_count": len(docs),
            "total_tokens": sum(c.values()),
            "unique_tokens": len(c),
            "elapsed_s": round(time.time() - t, 1),
        }
        print(
            f"[02] {name}: msg={len(docs)} tokens={stats[name]['total_tokens']:,} "
            f"unique={stats[name]['unique_tokens']:,} elapsed={stats[name]['elapsed_s']}s"
        )
    (freqs_dir / "openclaw_stats.json").write_text(json.dumps(stats, indent=2))
    print(f"[02] done -> {freqs_dir / 'openclaw_stats.json'}")


# ── Stage 03: build public corpus counters ─────────────────────────────────

def build_public_counters(
    model: str,
    freqs_dir: Path,
    skip_streaming: bool = False,
    c4_target_tokens: int = 5_000_000,
    sharegpt_target_tokens: int = 2_000_000,
    wildchat_target_tokens: int = 2_000_000,
    c4_shard: str | None = None,
    ceval_glob: str | None = None,
    legacy_csv: str | None = None,
) -> None:
    """Build public corpus counters (stage 03)."""
    import glob as _glob
    import pyarrow.parquet as pq

    freqs_dir.mkdir(parents=True, exist_ok=True)
    tok = AutoTokenizer.from_pretrained(model)
    stats: dict = {}
    CJK_RE = re.compile(r"[一-鿿]")

    _c4_shard = c4_shard or os.environ.get(
        "C4_SHARD",
        "/data01/home/yujy/.cache/huggingface/hub/datasets--allenai--c4/snapshots/"
        "1588ec454efa1a09f29cd18ddd04fe05fc8653a2/en/c4-train.00000-of-01024.json.gz",
    )
    _ceval_glob = ceval_glob or os.environ.get(
        "CEVAL_GLOB",
        "/data01/home/yujy/.cache/huggingface/hub/datasets--ceval--ceval-exam/"
        "snapshots/*/*/*.parquet",
    )
    _legacy_csv = legacy_csv or os.environ.get(
        "LEGACY_CSV",
        str(_PROJECT_ROOT / "analysis" / "mtp_head_longtail" / "freq_stats.csv"),
    )

    # CEval
    t0 = time.time()
    ceval_files = sorted(_glob.glob(_ceval_glob))
    print(f"[03/ceval] {len(ceval_files)} parquet shards")
    c: Counter = Counter()
    docs = 0
    for fp in ceval_files:
        tab = pq.read_table(fp)
        texts = []
        for row in tab.to_pylist():
            parts = [row.get(col, "") or "" for col in (
                "question", "A", "B", "C", "D", "answer", "explanation"
            )]
            joined = "\n".join(str(p) for p in parts if p)
            if joined:
                texts.append(joined)
        docs += len(texts)
        for i in range(0, len(texts), 64):
            enc = tok(texts[i:i+64], add_special_tokens=False)
            for ids in enc["input_ids"]:
                c.update(ids)
    torch.save(dict(c), freqs_dir / "public_ceval_zh.counter.pt")
    stats["ceval_zh"] = {
        "docs": docs, "tokens": sum(c.values()), "unique": len(c),
        "elapsed_s": round(time.time() - t0, 1),
    }
    print(f"[03/ceval] docs={docs} tokens={stats['ceval_zh']['tokens']:,}")

    # c4-en
    t0 = time.time()
    c = Counter()
    docs = 0
    buf: list[str] = []
    with gzip.open(_c4_shard, "rt") as f:
        for line in f:
            if sum(c.values()) >= c4_target_tokens:
                break
            try:
                d = json.loads(line)
            except Exception:
                continue
            text = d.get("text", "")
            if not text:
                continue
            buf.append(text)
            docs += 1
            if len(buf) >= 64:
                enc = tok(buf, add_special_tokens=False)
                for ids in enc["input_ids"]:
                    c.update(ids)
                buf.clear()
    if buf:
        enc = tok(buf, add_special_tokens=False)
        for ids in enc["input_ids"]:
            c.update(ids)
    torch.save(dict(c), freqs_dir / "public_c4_en.counter.pt")
    stats["c4_en"] = {
        "docs": docs, "tokens": sum(c.values()), "unique": len(c),
        "elapsed_s": round(time.time() - t0, 1),
    }
    print(f"[03/c4-en] docs={docs} tokens={stats['c4_en']['tokens']:,}")

    # Legacy CSV
    t0 = time.time()
    c = Counter()
    with open(_legacy_csv) as f:
        r = csv.DictReader(f)
        for row in r:
            tid = int(row["token_id"])
            cnt = int(row["freq_count"])
            if cnt > 0:
                c[tid] = cnt
    torch.save(dict(c), freqs_dir / "public_legacy.counter.pt")
    stats["legacy"] = {
        "tokens": sum(c.values()), "unique": len(c),
        "elapsed_s": round(time.time() - t0, 1),
    }
    print(f"[03/legacy] tokens={stats['legacy']['tokens']:,} unique={stats['legacy']['unique']:,}")

    if not skip_streaming:
        # ShareGPT-Chinese-English-90k
        t0 = time.time()
        c = Counter()
        total_tok = 0
        docs = 0
        try:
            from datasets import load_dataset
            ds = load_dataset(
                "shareAI/ShareGPT-Chinese-English-90k", split="train", streaming=True
            )
            buf = []
            for row in ds:
                convs = row.get("conversations") or row.get("conversation") or []
                for turn in convs:
                    role = turn.get("from", "") or turn.get("role", "")
                    text = turn.get("value", "") or turn.get("content", "")
                    if role not in ("gpt", "assistant") or not text:
                        continue
                    if not CJK_RE.search(text):
                        continue
                    buf.append(text)
                    docs += 1
                    if len(buf) >= 64:
                        enc = tok(buf, add_special_tokens=False)
                        for ids in enc["input_ids"]:
                            c.update(ids)
                            total_tok += len(ids)
                        buf.clear()
                    if total_tok >= sharegpt_target_tokens:
                        break
                if total_tok >= sharegpt_target_tokens:
                    break
            if buf:
                enc = tok(buf, add_special_tokens=False)
                for ids in enc["input_ids"]:
                    c.update(ids)
                    total_tok += len(ids)
            torch.save(dict(c), freqs_dir / "public_sharegpt_zh.counter.pt")
            stats["sharegpt_zh"] = {
                "docs": docs, "tokens": total_tok, "unique": len(c),
                "elapsed_s": round(time.time() - t0, 1),
            }
            print(f"[03/sharegpt_zh] docs={docs} tokens={total_tok:,} unique={len(c):,}")
        except Exception as e:
            print(f"[03/sharegpt_zh] SKIPPED: {e}")

        # WildChat-1M
        t0 = time.time()
        c = Counter()
        total_tok = 0
        docs = 0
        try:
            from datasets import load_dataset
            ds = load_dataset("allenai/WildChat-1M", split="train", streaming=True)
            buf = []
            for row in ds:
                lang = row.get("language", "") or ""
                if lang != "Chinese":
                    continue
                convs = row.get("conversation") or []
                for turn in convs:
                    role = turn.get("role", "")
                    text = turn.get("content", "")
                    if role != "assistant" or not text:
                        continue
                    buf.append(text)
                    docs += 1
                    if len(buf) >= 64:
                        enc = tok(buf, add_special_tokens=False)
                        for ids in enc["input_ids"]:
                            c.update(ids)
                            total_tok += len(ids)
                        buf.clear()
                    if total_tok >= wildchat_target_tokens:
                        break
                if total_tok >= wildchat_target_tokens:
                    break
            if buf:
                enc = tok(buf, add_special_tokens=False)
                for ids in enc["input_ids"]:
                    c.update(ids)
                    total_tok += len(ids)
            torch.save(dict(c), freqs_dir / "public_wildchat_zh.counter.pt")
            stats["wildchat_zh"] = {
                "docs": docs, "tokens": total_tok, "unique": len(c),
                "elapsed_s": round(time.time() - t0, 1),
            }
            print(f"[03/wildchat_zh] docs={docs} tokens={total_tok:,} unique={len(c):,}")
        except Exception as e:
            print(f"[03/wildchat_zh] SKIPPED: {e}")
    else:
        print("[03] skip_streaming=True — skipping ShareGPT and WildChat download")

    (freqs_dir / "public_stats.json").write_text(json.dumps(stats, indent=2))
    print(f"[03] done -> {freqs_dir / 'public_stats.json'}")


# ── Stage 04: weighted merge + hot_ids selection ─────────────────────────────

_WEIGHTS = {
    "openclaw_codex":     0.30,
    "openclaw_copilot":   0.18,
    "openclaw_vscode":    0.12,
    "public_c4_en":       0.10,
    "public_ceval_zh":    0.08,
    "public_sharegpt_zh": 0.10,
    "public_wildchat_zh": 0.08,
    "public_legacy":      0.04,
}
assert abs(sum(_WEIGHTS.values()) - 1.0) < 1e-6


def build_hot_ids(
    model: str,
    freqs_dir: Path,
    output_dir: Path,
    k_list: list[int],
    category_csv: Path | None = None,
    whitelist_path: Path | None = None,
) -> None:
    """Weighted-merge counters and select top-K hot ids (stage 04)."""
    output_dir.mkdir(parents=True, exist_ok=True)
    cfg = json.loads((Path(model) / "config.json").read_text(encoding="utf-8"))
    tc = cfg.get("text_config", cfg)
    V = int(tc["vocab_size"])
    H = int(tc["hidden_size"])
    print(f"[04] model V={V} H={H}")

    all_counters: dict[str, dict] = {}
    for name in _WEIGHTS:
        path = freqs_dir / f"{name}.counter.pt"
        if not path.exists():
            print(f"[04] WARNING: {path} not found, skipping (weight redistributed)")
            continue
        all_counters[name] = torch.load(path)
        print(
            f"[04] {name}: unique={len(all_counters[name])} "
            f"total={sum(all_counters[name].values()):,}"
        )

    active_w = {n: _WEIGHTS[n] for n in all_counters}
    w_sum = sum(active_w.values())
    active_w = {n: w / w_sum for n, w in active_w.items()}
    print(f"[04] active sources: {len(active_w)}/{len(_WEIGHTS)} (renormalized)")

    merged: dict[int, float] = {}
    totals: dict[str, int] = {}
    for name, cnt in all_counters.items():
        tot = sum(cnt.values()) or 1
        totals[name] = tot
        w = active_w[name]
        for tid, f in cnt.items():
            merged[tid] = merged.get(tid, 0.0) + (f / tot) * w
    print(f"[04] merged unique tokens: {len(merged):,}")
    torch.save(merged, output_dir / "merged_counter.pt")

    # Hard-keep structural tokens
    _cat_csv = category_csv or _CATEGORY_CSV
    cat_of: dict[int, str] = {}
    if _cat_csv.exists():
        with _cat_csv.open() as f:
            r = csv.DictReader(f)
            for row in r:
                cat_of[int(row["token_id"])] = row["category"]

    HARD_CATS = {"special", "punct", "digit", "emoji", "space", "ctrl", "bpe_partial"}
    hard_hot: set[int] = {tid for tid, c in cat_of.items() if c in HARD_CATS}

    tok = AutoTokenizer.from_pretrained(model)
    for tid in tok.all_special_ids:
        hard_hot.add(tid)
    for tid in tok.added_tokens_decoder.keys():
        hard_hot.add(int(tid))

    _wl = whitelist_path or (
        _V2_ROOT / "extras" / "dialogue_whitelist.json"
    )
    whitelist_added: list = []
    if _wl.exists():
        wl = json.loads(_wl.read_text(encoding="utf-8"))
        for key, val in wl.items():
            if key.startswith("_") or not isinstance(val, list):
                continue
            for s in val:
                ids = tok(s, add_special_tokens=False).input_ids
                for t in ids:
                    if 0 <= t < V and t not in hard_hot:
                        hard_hot.add(t)
                        whitelist_added.append((key, s, t))
        print(
            f"[04] whitelist: {len(whitelist_added)} new tokens forced hot from {_wl}"
        )

    hard_hot = {tid for tid in hard_hot if 0 <= tid < V}
    print(f"[04] hard-keep (structural): {len(hard_hot)} tokens")

    ranked = sorted(merged.items(), key=lambda kv: -kv[1])
    stats_out = {
        "V": V, "H": H, "weights": _WEIGHTS, "source_totals": totals,
        "hard_hot_count": len(hard_hot), "results": {},
    }

    for K in k_list:
        if K <= len(hard_hot):
            raise RuntimeError(f"K={K} <= hard={len(hard_hot)}")
        budget = K - len(hard_hot)
        extras: list[int] = []
        seen: set[int] = set(hard_hot)
        for tid, _ in ranked:
            if len(extras) >= budget:
                break
            if tid in seen or tid < 0 or tid >= V:
                continue
            extras.append(tid)
            seen.add(tid)
        for tid in range(V):
            if len(extras) >= budget:
                break
            if tid in seen:
                continue
            extras.append(tid)
            seen.add(tid)

        hot_ids = sorted(list(hard_hot) + extras)
        assert len(hot_ids) == K

        hot_t = torch.tensor(hot_ids, dtype=torch.int64)
        old_to_new = torch.full((V,), -1, dtype=torch.int64)
        old_to_new[hot_t] = torch.arange(K, dtype=torch.int64)
        new_to_old = hot_t.clone()

        torch.save(hot_t, output_dir / f"hot_ids_{K}.pt")
        torch.save(
            {"old_to_new": old_to_new, "new_to_old": new_to_old},
            output_dir / f"id_map_{K}.pt",
        )

        hot_set = set(hot_ids)
        cov: dict[str, float] = {}
        for name, cnt in all_counters.items():
            tot = sum(cnt.values()) or 1
            hit = sum(f for tid, f in cnt.items() if tid in hot_set)
            cov[name] = round(hit / tot * 100, 3)
        cov["weighted"] = round(sum(active_w[n] * cov[n] for n in active_w), 3)

        head_mb = K * H * 2 / 1024 / 1024
        oc_w = sum(active_w[n] for n in active_w if n.startswith("openclaw"))
        pub_w = sum(active_w[n] for n in active_w if n.startswith("public"))
        stats_out["results"][f"K_{K}"] = {
            "K": K, "hard": len(hard_hot), "extras": len(extras),
            "coverage_per_source": cov,
            "head_bf16_mb": round(head_mb, 2),
            "head_w4_mb_approx": round(head_mb / 4, 2),
            "io_saving_pct": round(
                (1 - head_mb / (V * H * 2 / 1024 / 1024)) * 100, 2
            ),
        }
        oc_cov = (
            sum(active_w[n] * cov[n] for n in active_w if n.startswith("openclaw"))
            / oc_w
        )
        pub_cov = (
            sum(active_w[n] * cov[n] for n in active_w if n.startswith("public"))
            / pub_w
        )
        print(
            f"[04] K={K} cov_weighted={cov['weighted']}% "
            f"cov_openclaw={oc_cov:.3f}% "
            f"cov_public={pub_cov:.3f}% "
            f"head_bf16={head_mb:.1f}MB"
        )

    (output_dir / "selection_stats.json").write_text(
        json.dumps(stats_out, indent=2, ensure_ascii=False)
    )
    print(f"[04] done -> {output_dir / 'selection_stats.json'}")


# ── CLI ───────────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--model",
        default=str(_PROJECT_ROOT / "weights" / "Qwen3.5-4B"),
        help="Path to the Qwen3.5 model directory (tokenizer source).",
    )
    parser.add_argument(
        "--corpus-dir",
        default=str(_V2_ROOT / "corpus"),
        help="Directory containing openclaw_raw.tsv.",
    )
    parser.add_argument(
        "--freqs-dir",
        default=str(_V2_ROOT / "freqs"),
        help="Directory for reading/writing .counter.pt files.",
    )
    parser.add_argument(
        "--output-dir",
        default=str(_V2_ROOT / "selection"),
        help="Output directory for hot_ids_*.pt / id_map_*.pt / selection_stats.json.",
    )
    parser.add_argument(
        "--k-list",
        default="32000,48000,81920,82000",
        help="Comma-separated list of K values to generate (default: 32000,48000,81920,82000).",
    )
    parser.add_argument(
        "--skip-public",
        action="store_true",
        help=(
            "Skip re-building public corpus counters from HF datasets. "
            "Assumes freqs/public_*.counter.pt already exist."
        ),
    )
    parser.add_argument(
        "--rebuild-counters",
        action="store_true",
        help=(
            "Rebuild openclaw counter files from corpus/openclaw_raw.tsv (stage 02). "
            "By default this stage is skipped if *.counter.pt already exist."
        ),
    )
    args = parser.parse_args()

    k_list = [int(k) for k in args.k_list.split(",")]
    freqs_dir = Path(args.freqs_dir)
    output_dir = Path(args.output_dir)
    corpus_dir = Path(args.corpus_dir)

    # Stage 02 — openclaw counters
    openclaw_files = [
        freqs_dir / f"openclaw_{s}.counter.pt"
        for s in ("codex", "copilot", "vscode")
    ]
    need_openclaw = args.rebuild_counters or not all(f.exists() for f in openclaw_files)
    if need_openclaw:
        print("[build] Stage 02: building openclaw counters ...")
        build_openclaw_counters(args.model, corpus_dir, freqs_dir)
    else:
        print("[build] Stage 02: openclaw counters exist — skipping (pass --rebuild-counters to force).")

    # Stage 03 — public counters
    public_names = ["ceval_zh", "c4_en", "legacy"]  # sharegpt/wildchat optional
    public_files = [freqs_dir / f"public_{n}.counter.pt" for n in public_names]
    need_public = not args.skip_public and not all(f.exists() for f in public_files)
    if args.skip_public:
        print("[build] Stage 03: --skip-public set — skipping public counter rebuild.")
        for f in public_files:
            if not f.exists():
                print(f"[build] WARNING: expected {f} not found — merge may use fewer sources.")
    elif need_public:
        print("[build] Stage 03: building public counters ...")
        build_public_counters(args.model, freqs_dir)
    else:
        print("[build] Stage 03: public counters exist — skipping (omit --skip-public to force).")

    # Stage 04 — merge + select
    print(f"[build] Stage 04: weighted merge + selecting hot_ids for K={k_list} ...")
    build_hot_ids(args.model, freqs_dir, output_dir, k_list)

    print(f"\n[build] Done. Outputs in {output_dir}")
    for K in k_list:
        hf = output_dir / f"hot_ids_{K}.pt"
        if hf.exists():
            print(f"  hot_ids_{K}.pt  size={hf.stat().st_size//1024}KB")


if __name__ == "__main__":
    main()
