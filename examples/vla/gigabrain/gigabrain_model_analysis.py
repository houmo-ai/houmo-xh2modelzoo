"""
┌─────────────────────────────────────────────────────────────────────────────────┐
│                          GigaBrain 完整推理流程                                  │
├─────────────────────────────────────────────────────────────────────────────────┤
│                                                                                  │
│  阶段 1: 图像编码 (Vision Encoder)                                              │
│  ┌──────────────────────────────────────────────────────────────────────────┐   │
│  │ 输入: images (B, 3, 224, 224) - 3 个相机视角                              │   │
│  │ 处理:                                                                     │   │
│  │   1. SigLIP ViT Embedding: patch_size=14, 输出 256 tokens                │   │
│  │   2. SigLIP Encoder: 27 层 Transformer                                    │   │
│  │   3. Post LayerNorm                                                       │   │
│  │   4. Projector: 1152 → 2304                                               │   │
│  │ 输出: image_features (B, 256, 2304)                                       │   │
│  └──────────────────────────────────────────────────────────────────────────┘   │
│                                       │                                          │
│                                       ▼                                          │
│  阶段 2: 语言编码 (Language Processing)                                         │
│  ┌──────────────────────────────────────────────────────────────────────────┐   │
│  │ 输入: task_prompt = "Pick up the red block and place it in the bin"      │   │
│  │ 处理:                                                                     │   │
│  │   1. Gemma2 Tokenizer: text → input_ids (B, seq_len)                     │   │
│  │   2. Token Embedding: input_ids → lang_embeds (B, seq_len, 2304)         │   │
│  │ 输出: lang_embeds (B, seq_len, 2304)                                      │   │
│  └──────────────────────────────────────────────────────────────────────────┘   │
│                                       │                                          │
│                                       ▼                                          │
│  阶段 3: LLM Prefill (生成 KV Cache)                                            │
│  ┌──────────────────────────────────────────────────────────────────────────┐   │
│  │ 输入:                                                                     │   │
│  │   - image_features (B, 256, 2304)                                        │   │
│  │   - lang_embeds (B, seq_len, 2304)                                       │   │
│  │ 处理:                                                                     │   │
│  │   1. Concat: [image_features, lang_embeds] → inputs_embeds               │   │
│  │   2. LLM Prefill (26 层 Gemma2):                                         │   │
│  │      - Self-Attention with GQA (8Q, 4KV)                                 │   │
│  │      - RMSNorm + Gated Residual                                          │   │
│  │      - MLP (intermediate=9216)                                           │   │
│  │   3. 生成并保存 KV Cache (用于后续 Expert 推理)                            │   │
│  │ 输出:                                                                     │   │
│  │   - logits (B, total_seq, 256000) - 可用于生成子任务描述                  │   │
│  │   - KV Cache: K/V tensors per layer                                      │   │
│  └──────────────────────────────────────────────────────────────────────────┘   │
│                                       │                                          │
│                                       │ KV Cache                                 │
│                                       ▼                                          │
│  阶段 4: 动作生成 (Flow Matching 扩散)                                          │
│  ┌──────────────────────────────────────────────────────────────────────────┐   │
│  │ for t in timesteps (从 T 到 0):                                          │   │
│  │                                                                           │   │
│  │   4.1 噪声采样                                                            │   │
│  │   ┌────────────────────────────────────────────────────────────────┐     │   │
│  │   │ noise = sample_noise(shape=(B, 50, 32))                        │     │   │
│  │   │ action_t = action_prev + noise * t                             │     │   │
│  │   └────────────────────────────────────────────────────────────────┘     │   │
│  │                                                                           │   │
│  │   4.2 动作嵌入                                                            │   │
│  │   ┌────────────────────────────────────────────────────────────────┐     │   │
│  │   │ action_emb = action_in_proj(action_t, emb_ids)                 │     │   │
│  │   │ # (B, 50, 32) → (B, 50, 1024)                                  │     │   │
│  │   └────────────────────────────────────────────────────────────────┘     │   │
│  │                                                                           │   │
│  │   4.3 时间步编码                                                          │   │
│  │   ┌────────────────────────────────────────────────────────────────┐     │   │
│  │   │ time_emb = sinusoidal_embedding(t, dim=1024)                   │     │   │
│  │   │ cond = time_mlp(time_emb)  # AdaRMS condition                  │     │   │
│  │   │ # (B, 1024) → (B, 1024)                                        │     │   │
│  │   └────────────────────────────────────────────────────────────────┘     │   │
│  │                                                                           │   │
│  │   4.4 Expert Prefill/Decode (使用 LLM 的 KV Cache)                       │   │
│  │   ┌────────────────────────────────────────────────────────────────┐     │   │
│  │   │ # Prefill: 处理整个 action 序列                                 │     │   │
│  │   │ hidden = Expert_Prefill(action_emb, cond, KV_Cache_from_LLM)   │     │   │
│  │   │ # (B, 50, 1024) → (B, 50, 1024)                                │     │   │
│  │   │                                                                │     │   │
│  │   │ # Decode: 单步解码 (可选，用于生成更长序列)                       │     │   │
│  │   │ for step in range(50):                                         │     │   │
│  │   │     hidden[:, step:step+1] = Expert_Decode(                    │     │   │
│  │   │         action_emb[:, step:step+1], cond, KV_Cache             │     │   │
│  │   │     )                                                          │     │   │
│  │   └────────────────────────────────────────────────────────────────┘     │   │
│  │                                                                           │   │
│  │   4.5 动作输出                                                            │   │
│  │   ┌────────────────────────────────────────────────────────────────┐     │   │
│  │   │ v_t = action_out_proj(hidden, emb_ids)                         │     │   │
│  │   │ # (B, 50, 1024) → (B, 50, 32)                                  │     │   │
│  │   │ # v_t 是去噪速度场                                              │     │   │
│  │   └────────────────────────────────────────────────────────────────┘     │   │
│  │                                                                           │   │
│  │   4.6 Flow Matching 更新                                                  │   │
│  │   ┌────────────────────────────────────────────────────────────────┐     │   │
│  │   │ action_prev = action_prev - v_t * dt                           │     │   │
│  │   └────────────────────────────────────────────────────────────────┘     │   │
│  └──────────────────────────────────────────────────────────────────────────┘   │
│                                       │                                          │
│                                       ▼                                          │
│  阶段 5: 后处理 (Post-processing)                                               │
│  ┌──────────────────────────────────────────────────────────────────────────┐   │
│  │ 输入: action (B, 50, 32) - 相对动作序列                                  │   │
│  │ 处理:                                                                     │   │
│  │   1. Unnormalize: 根据机器人类型反归一化                                  │   │
│  │   2. Convert to Absolute: 相对动作 → 绝对动作                             │   │
│  │   3. Clip: 限制动作范围                                                   │   │
│  │ 输出: absolute_actions (B, 50, action_dim)                               │   │
│  │       action_dim 取决于机器人类型 (14/20/32)                             │   │
│  └──────────────────────────────────────────────────────────────────────────┘   │
│                                                                                  │
└─────────────────────────────────────────────────────────────────────────────────┘
"""

